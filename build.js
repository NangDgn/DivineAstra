// Builds src/index.js (the Wasmer Edge worker) from index.html.
// Usage:  node build.js YOUR_TURNSTILE_SITE_KEY
// Run it again every time you edit index.html.
const fs = require('fs');
const path = require('path');

const siteKey = process.argv[2];
let html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');

if (siteKey) {
  html = html.replace('YOUR_TURNSTILE_SITE_KEY', siteKey);
} else if (html.includes('YOUR_TURNSTILE_SITE_KEY')) {
  console.warn('\n! No site key given. The captcha will not work until you run:\n  node build.js YOUR_TURNSTILE_SITE_KEY\n');
}

const worker = `// Generated by build.js. Edit index.html and re-run the build instead of editing this file.
const HTML = ${JSON.stringify(html)};

const SECURITY_HEADERS = {
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
  'Content-Security-Policy': "default-src 'self'; script-src 'self' 'unsafe-inline' https://challenges.cloudflare.com; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; img-src 'self' data: https://cdn.corenexis.com; connect-src 'self' https://challenges.cloudflare.com; frame-src https://challenges.cloudflare.com; base-uri 'self'; form-action 'self'; object-src 'none'"
};

function env(name) {
  try { return (typeof process !== 'undefined' && process.env && process.env[name]) || ''; }
  catch (_) { return ''; }
}

function json(body, status) {
  return new Response(JSON.stringify(body), {
    status: status || 200,
    headers: Object.assign({ 'Content-Type': 'application/json', 'Cache-Control': 'no-store' }, SECURITY_HEADERS)
  });
}

/* Best-effort rate limit: 5 unlock attempts per IP per 60 s.
   Only used when the platform tells us the visitor IP. */
const hits = new Map();
function limited(ip) {
  if (!ip) return false;
  const now = Date.now();
  const arr = (hits.get(ip) || []).filter(function (t) { return now - t < 60000; });
  arr.push(now);
  hits.set(ip, arr);
  if (hits.size > 5000) {
    hits.forEach(function (v, k) { if (!v.length || now - v[v.length - 1] > 60000) hits.delete(k); });
  }
  return arr.length > 5;
}

async function unlock(request) {
  if (request.method !== 'POST') return json({ error: 'method not allowed' }, 405);

  /* Optional: set ALLOWED_ORIGINS="https://your-app.wasmer.app,https://yourdomain.com" */
  const allowed = env('ALLOWED_ORIGINS').split(',').map(function (s) { return s.trim(); }).filter(Boolean);
  const origin = request.headers.get('origin');
  if (allowed.length && origin && allowed.indexOf(origin) === -1) return json({ error: 'forbidden' }, 403);

  const fwd = request.headers.get('x-forwarded-for') || request.headers.get('cf-connecting-ip') || '';
  const ip = fwd.split(',')[0].trim();
  if (limited(ip)) return json({ error: 'too many requests' }, 429);

  let token = '';
  try { token = (await request.json()).token; } catch (_) { return json({ error: 'bad request' }, 400); }
  if (!token || typeof token !== 'string' || token.length > 2048) return json({ error: 'bad request' }, 400);

  const form = new URLSearchParams();
  form.set('secret', env('TURNSTILE_SECRET'));
  form.set('response', token);
  if (ip) form.set('remoteip', ip);

  let check = { success: false };
  try {
    const r = await fetch('https://challenges.cloudflare.com/turnstile/v0/siteverify', { method: 'POST', body: form });
    check = await r.json();
  } catch (_) {}

  if (!check.success) return json({ error: 'verification failed' }, 403);
  return json({ url: env('TOOLS_URL') });
}

async function handler(request) {
  const path = new URL(request.url).pathname;
  if (path === '/api/unlock') return unlock(request);
  if (path === '/' || path === '/index.html') {
    return new Response(HTML, {
      headers: Object.assign({ 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'public, max-age=300' }, SECURITY_HEADERS)
    });
  }
  return new Response('Not found', { status: 404, headers: SECURITY_HEADERS });
}

addEventListener('fetch', function (event) { event.respondWith(handler(event.request)); });
`;

fs.mkdirSync(path.join(__dirname, 'src'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'src', 'index.js'), worker);
console.log('Built src/index.js (' + Math.round(worker.length / 1024) + ' KB)');
